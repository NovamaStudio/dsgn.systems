async function dsgnStatus() {
  const cols = await figma.variables.getLocalVariableCollectionsAsync();
  const prim = cols.find((c) => c.name === 'Primitives');
  if (!prim) return { library: false };
  const saved = {};
  for (const m of prim.modes.slice(1)) saved[m.name] = prim.getSharedPluginData('dsgn', 'theme:' + m.name) || '';
  return { library: true, themes: prim.modes.slice(1).map((m) => m.name), saved, file: figma.root.name };
}
