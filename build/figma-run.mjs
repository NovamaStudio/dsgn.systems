// Shared plumbing for the scripts that run inside Figma (dist/figma-parity.js, figma-handoff.js,
// figma-lint.js) and the build's sync check.
//
// Every script is wrapped so its result also carries
//   code   a fingerprint of the script itself (= of the code, tokens and map it was built from)
//   figma  a fingerprint of the Figma file it ran on (figma/figma-state.js)
// Save each result as figma/<name>-report.json. `checkSync()` then fails the build when a report
// is missing, not ok, built from older code, or when the three reports were not all run on the
// same state of the Figma file. Change anything in code or Figma → run all three again.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const STATE = readFileSync(new URL('../figma/figma-state.js', import.meta.url), 'utf8');
export const SCRIPTS = ['parity', 'handoff', 'lint'];
const fpFile = new URL('../dist/figma-fingerprints.json', import.meta.url);

export function writeFigmaScript(name, body) {
  const code = createHash('sha1').update(STATE).update(body).digest('hex').slice(0, 12);
  const script = `// dsgn ${name} — generated by the build, do not edit. Run it in the dsgn Figma file (use_figma) and save the result as figma/${name}-report.json.\n` +
    STATE + '\nconst __result = await (async () => {\n' + body + '\n})();\n' +
    `return Object.assign(__result, { script: '${name}', code: '${code}', figma: await __figmaState() });\n`;
  writeFileSync(new URL(`../dist/figma-${name}.js`, import.meta.url), script);
  const fps = existsSync(fpFile) ? JSON.parse(readFileSync(fpFile, 'utf8')) : {};
  fps[name] = code; writeFileSync(fpFile, JSON.stringify(fps, null, 1));
  if (script.length > 49000) { console.error(`✗ figma-${name}.js exceeds the 50 kB MCP limit`); process.exit(1); }
  return script;
}

export function checkSync() {
  const fps = JSON.parse(readFileSync(fpFile, 'utf8'));
  const problems = [], states = {};
  for (const name of SCRIPTS) {
    const f = new URL(`../figma/${name}-report.json`, import.meta.url);
    if (!existsSync(f)) { problems.push(`${name}: no report`); continue; }
    const r = JSON.parse(readFileSync(f, 'utf8'));
    if (!r.ok) problems.push(`${name}: the last run found problems`);
    if (r.code !== fps[name]) problems.push(`${name}: report is from older code (${r.code || 'no fingerprint'} ≠ ${fps[name]})`);
    states[name] = r.figma;
  }
  const distinct = [...new Set(Object.values(states))];
  if (distinct.length > 1 || distinct[0] === undefined) problems.push('reports were run on different states of the Figma file: ' + SCRIPTS.map((n) => `${n} ${states[n] || '—'}`).join(', '));
  if (problems.length) {
    console.error('✗ Figma is not in sync with the code:\n  - ' + problems.join('\n  - ') +
      '\n  Run in Figma, in this order, and save each result as figma/<name>-report.json:' +
      '\n    (dist/figma-sync.js first if tokens changed) → dist/figma-parity.js → dist/figma-handoff.js → dist/figma-lint.js');
    process.exit(1);
  }
  console.log(`sync: parity, handoff and lint ran on the current code and the same Figma state (${distinct[0]}) ✓`);
}
