// Figma ↔ code handoff (Code Connect substitute). Checks src/docs/figma-map.mjs against the docs
// and writes dist/figma-handoff.js: a Figma Plugin API script (run it through the Figma MCP or a
// scratch plugin in the library file) that writes a "Code" section into every component's
// description — the snippet, how each property value is written in code, and the docs link — and
// sets the component's documentation link. Variants get the attributes of that exact variant.
// It returns { ok, updated, missing[], unmapped[] }; save it as figma/handoff-report.json.
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { components } from '../src/docs/examples.mjs';
import { figmaMap, STATE } from '../src/docs/figma-map.mjs';

const DOCS = 'https://novamastudio.github.io/dsgn.systems/';
const errors = [];
const docNames = new Set();
for (const [id, c] of Object.entries(components)) for (const n of c.figma || []) if (!/\(|…|\//.test(n)) docNames.add(n);
for (const [name, e] of Object.entries(figmaMap)) if (!components[e.doc]) errors.push(`${name}: docs page "${e.doc}" does not exist`);
for (const n of docNames) if (!figmaMap[n] && !/example/i.test(n)) errors.push(`${n}: listed in the docs but has no entry in figma-map.mjs`);
if (errors.length) { for (const e of errors) console.error('✗ handoff', e); process.exit(1); }

const script = `// dsgn handoff — generated by build/handoff.mjs, do not edit
const M = ${JSON.stringify(figmaMap)};
const S = ${JSON.stringify(STATE)};
const DOCS = ${JSON.stringify(DOCS)};
const MARK = '\\n\\n**— Code —**\\n';
// description reads back HTML-escaped; descriptionMarkdown reads back as written. Unescape older
// round-trips, keep the designer's text above the marker, and write markdown (code in backticks).
const unesc = (t) => { let p; do { p = t; t = t.replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'"); } while (t !== p); return t; };
const strip = (n) => unesc(n.descriptionMarkdown || n.description || '').split(/\\n\\n\\*{0,2}— Code —\\*{0,2}\\n/)[0].replace(/^\\*{0,2}— Code —\\*{0,2}\\n[\\s\\S]*$/, '').trim();
const BT = String.fromCharCode(96);
const tick = (f) => /[<=:]/.test(f) ? BT + f + BT : f;
const frag = (e, prop, val) => { const p = e.props && e.props[prop]; if (p && val in p) return p[val]; if (prop === 'State' && val in S) return S[val]; return undefined; };
let updated = 0; const missing = [], unmapped = [];
for (const page of figma.root.children) {
  if (page.name === 'Templates') continue;
  await page.loadAsync();
  for (const n of page.findAll((x) => x.type === 'COMPONENT_SET' || (x.type === 'COMPONENT' && x.parent.type !== 'COMPONENT_SET'))) {
    const e = M[n.name];
    if (!e) { missing.push(page.name + ' › ' + n.name); continue; }
    const defs = n.componentPropertyDefinitions || {};
    const lines = [BT + e.code + BT];
    for (const [key, d] of Object.entries(defs)) {
      const prop = key.split('#')[0];
      if (d.type === 'VARIANT') {
        const parts = d.variantOptions.map((v) => { const f = frag(e, prop, v); if (f === undefined) { unmapped.push(n.name + ' · ' + prop + '=' + v); return v + ' → (Figma only)'; } return v + ' → ' + (f === '' ? 'default' : tick(f)); });
        lines.push(prop + ': ' + parts.join(' · '));
      } else if (d.type === 'BOOLEAN' && e.bools && e.bools[prop]) lines.push(prop + ': on → ' + tick(e.bools[prop]));
    }
    lines.push('Docs: ' + DOCS + '#' + e.doc);
    const base = strip(n);
    n.descriptionMarkdown = (base ? base + MARK : '**— Code —**\\n') + lines.join('  \\n');
    try { n.documentationLinks = [{ uri: DOCS + '#' + e.doc }]; } catch (err) {}
    if (n.type === 'COMPONENT_SET') for (const v of n.children) {
      const attrs = Object.entries(v.variantProperties || {}).map(([prop, val]) => frag(e, prop, val)).filter((f) => f);
      const vb = strip(v);
      v.descriptionMarkdown = (vb ? vb + MARK : '**— Code —**\\n') + (attrs.length ? attrs.map(tick).join(' · ') : 'defaults: ' + BT + e.code + BT);
    }
    updated++;
  }
}
return { ok: missing.length === 0 && unmapped.length === 0, updated, missing, unmapped };
`;
writeFileSync(new URL('../dist/figma-handoff.js', import.meta.url), script);
console.log(`figma-handoff.js written (${Object.keys(figmaMap).length} components, ${(script.length / 1024).toFixed(1)} kB) — run it in Figma, save the result as figma/handoff-report.json`);
if (script.length > 49000) { console.error('✗ handoff script exceeds the 50 kB MCP limit'); process.exit(1); }

const rep = new URL('../figma/handoff-report.json', import.meta.url);
if (existsSync(rep)) { const r = JSON.parse(readFileSync(rep, 'utf8')); if (!r.ok) { console.error('✗ handoff: last Figma run reported', r.missing.length, 'unmapped components and', r.unmapped.length, 'unmapped values (figma/handoff-report.json)'); process.exit(1); } console.log(`handoff: ${r.updated} Figma components carry their code ✓`); }
