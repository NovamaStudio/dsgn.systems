// Figma plugin "dsgn sync check": runs the generated Figma scripts unchanged, in the required order
// (figma-sync → figma-parity → figma-handoff → figma-lint), on the open library file, and shows all
// results as one JSON to copy. Save it with `node build/save-reports.mjs <file>` (or paste it to
// Claude), then `npm run build` checks the fingerprints as usual.
//
// A fallback for when the scripts cannot be run through the Figma MCP. Generated into
// figma-check-plugin/ and committed, so a local copy of the repository can import it once
// (Plugins → Development → Import plugin from manifest…) and always runs the current scripts.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const dist = (f) => readFileSync(new URL(`../dist/${f}`, import.meta.url), 'utf8');
const pkg = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
const dir = new URL('../figma-check-plugin/', import.meta.url);
mkdirSync(dir, { recursive: true });

const steps = ['sync', 'parity', 'handoff', 'lint'];
const fn = (name) => `async function run_${name}() {\n${dist(`figma-${name}.js`)}\n}`;

writeFileSync(new URL('manifest.json', dir), JSON.stringify({
  name: 'dsgn sync check',
  id: 'dsgn-sync-check-local',
  api: '1.0.0',
  main: 'code.js',
  ui: 'ui.html',
  editorType: ['figma'],
  documentAccess: 'dynamic-page',
  networkAccess: { allowedDomains: ['none'] },
}, null, 2) + '\n');

writeFileSync(new URL('code.js', dir), `// dsgn sync check ${pkg.version} — generated by build/check-plugin.mjs, do not edit.
// Runs dist/figma-sync.js, figma-parity.js, figma-handoff.js and figma-lint.js unchanged, in this order.
figma.showUI(__html__, { width: 520, height: 380 });
${steps.map(fn).join('\n')}
(async () => {
  const out = { version: '${pkg.version}' };
  for (const [name, run] of [${steps.map((s) => `['${s}', run_${s}]`).join(', ')}]) {
    figma.ui.postMessage({ step: name });
    try { out[name] = await run(); } catch (e) { out[name] = { ok: false, error: String((e && e.stack) || e) }; break; }
  }
  const ok = ['parity', 'handoff', 'lint'].every((n) => out[n] && out[n].ok);
  figma.ui.postMessage({ done: true, ok, text: JSON.stringify(out) });
})();
`);

writeFileSync(new URL('ui.html', dir), `<style>body{font:13px system-ui,sans-serif;margin:12px}textarea{width:100%;height:250px;font:11px ui-monospace,monospace;box-sizing:border-box}button{margin-top:8px;padding:6px 12px}#s{margin:0 0 8px}</style>
<p id="s">Running…</p>
<textarea id="t" readonly></textarea>
<button id="c">Copy result</button>
<script>
onmessage = (e) => { const m = e.data.pluginMessage; const s = document.getElementById('s');
  if (m.step) { s.textContent = 'Running ' + m.step + '…'; return; }
  s.textContent = m.ok ? 'Done — all checks passed. Copy the result and send it to Claude.' : 'Done with problems — copy the result and send it to Claude.';
  document.getElementById('t').value = m.text; };
document.getElementById('c').onclick = () => { const t = document.getElementById('t'); t.select(); document.execCommand('copy'); document.getElementById('c').textContent = 'Copied ✓'; };
</script>
`);
console.log(`figma-check-plugin/ written (${steps.join(' → ')})`);
