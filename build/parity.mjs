// Generates dist/figma-parity.js: a self-contained Figma Plugin API script that compares the
// Figma file with what the code says it should contain (dist/figma-variables.json).
// Run it via the Figma MCP (use_figma) or paste it into a scratch plugin; it changes nothing
// and returns { ok, summary, mismatches[] }. Save the result to figma/parity-report.json and
// run `node build/parity.mjs --report figma/parity-report.json` to turn it into Markdown.
//
// What is compared
//   collections  name, mode names and ORDER (the first mode is the default); extra modes after
//                them in Primitives / Typography are project themes and are only listed
//   variables    existence both ways, type, scopes, WEB code syntax, value per mode
//                (colours within 1/255 per channel, numbers exactly, aliases by target name)
//   text styles  existence, font family + weight, variable bindings of size and line-height
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const arg = (k) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : null; };

if (arg('--report')) {
  const r = JSON.parse(readFileSync(arg('--report'), 'utf8'));
  const lines = [`# Figma ↔ code parity`, '', `Checked ${new Date(r.checkedAt).toISOString().slice(0, 16).replace('T', ' ')} UTC · ${r.ok ? '**in sync**' : `**${r.mismatches.length} differences**`}`, '',
    '| What | Checked |', '|---|---|', ...Object.entries(r.summary).map(([k, n]) => `| ${k} | ${Array.isArray(n) ? n.join(', ') : n} |`), ''];
  if (r.mismatches.length) {
    lines.push('| Where | Problem | Code | Figma |', '|---|---|---|---|');
    for (const m of r.mismatches) lines.push(`| ${m.where} | ${m.problem} | ${m.code ?? ''} | ${m.figma ?? ''} |`);
  }
  writeFileSync(new URL('../dist/parity-report.md', import.meta.url), lines.join('\n') + '\n');
  console.log(r.ok ? 'parity: Figma and code are in sync ✓' : `parity: ${r.mismatches.length} differences → dist/parity-report.md`);
  process.exit(r.ok ? 0 : 1);
}

const payload = JSON.parse(readFileSync(new URL('../dist/figma-variables.json', import.meta.url), 'utf8'));
// compact encoding so the script stays small enough to paste through MCP:
// variable = [name, type(C/F/S), scopes csv, web ("x" = var(--dsgn-x)), values per mode ("@Coll::name" = alias)]
const T = { COLOR: 'C', FLOAT: 'F', STRING: 'S' };
const compact = { c: payload.collections.map((c) => ({ n: c.name, m: c.modes, v: c.variables.map((v) => {
  const w = v.codeSyntax && v.codeSyntax.WEB; const m = w && w.match(/^var\(--dsgn-([\w-]+)\)$/);
  return [v.name, T[v.type], (v.scopes || []).join(','), m ? m[1] : (w || ''), c.modes.map((mode) => { const x = v.values[mode]; return x && typeof x === 'object' ? '@' + x.alias : x; })];
}) })), t: payload.textStyles };

const checker = `// dsgn parity check — generated by build/parity.mjs, do not edit
const C = ${JSON.stringify(compact)};
const TY = { C: 'COLOR', F: 'FLOAT', S: 'STRING' };
const EXPECTED = { textStyles: C.t, collections: C.c.map((c) => ({ name: c.n, modes: c.m, variables: c.v.map(([name, t, sc, w, vals]) => ({ name, type: TY[t], scopes: sc ? sc.split(',') : [],
  codeSyntax: w ? { WEB: w.startsWith('var(') || w.startsWith('calc(') || w.startsWith('max(') || w.includes(' ') || w.includes('vw') ? w : 'var(--dsgn-' + w + ')' } : null,
  values: Object.fromEntries(c.m.map((m, i) => [m, typeof vals[i] === 'string' && vals[i][0] === '@' ? { alias: vals[i].slice(1) } : vals[i]])) })) })) };
const out = []; const summary = { collections: 0, variables: 0, values: 0, 'text styles': 0 };
const miss = (where, problem, code, figma) => out.push({ where, problem, code: code === undefined ? undefined : String(code), figma: figma === undefined ? undefined : String(figma) });
const hex2 = (n) => Math.round(n * 255).toString(16).padStart(2, '0');
const toHex = (c) => '#' + hex2(c.r) + hex2(c.g) + hex2(c.b) + (c.a !== undefined && c.a < 1 ? hex2(c.a) : '');
const parseHex = (h) => { const x = h.replace('#', ''); const p = (i) => parseInt(x.slice(i, i + 2), 16) / 255; return { r: p(0), g: p(2), b: p(4), a: x.length > 6 ? p(6) : 1 }; };
const sameColor = (a, b) => ['r', 'g', 'b', 'a'].every((k) => Math.abs((a[k] ?? 1) - (b[k] ?? 1)) <= 1.01 / 255);
const cols = await figma.variables.getLocalVariableCollectionsAsync();
const vars = await figma.variables.getLocalVariablesAsync();
const byId = Object.fromEntries(vars.map((v) => [v.id, v]));
const colName = Object.fromEntries(cols.map((c) => [c.id, c.name]));
const fullName = (v) => colName[v.variableCollectionId] + '::' + v.name;
for (const ec of EXPECTED.collections) {
  summary.collections++;
  const fc = cols.find((c) => c.name === ec.name);
  if (!fc) { miss(ec.name, 'collection missing in Figma', ec.modes.join(', '), '—'); continue; }
  const fm = fc.modes.map((m) => m.name);
  // project themes (dsgn theme) add modes after the package's own ones in Primitives and Typography
  const themeable = ec.name === 'Primitives' || ec.name === 'Typography';
  const extra = fm.slice(ec.modes.length);
  if (fm.slice(0, ec.modes.length).join('|') !== ec.modes.join('|') || (extra.length && !themeable)) miss(ec.name, 'modes or their order differ (first = default)', ec.modes.join(', '), fm.join(', '));
  else if (extra.length) summary['theme modes'] = [...new Set([...(summary['theme modes'] || []), ...extra])];
  const fvars = vars.filter((v) => v.variableCollectionId === fc.id);
  for (const ev of ec.variables) {
    summary.variables++;
    const where = ec.name + '/' + ev.name;
    const fv = fvars.find((v) => v.name === ev.name);
    if (!fv) { miss(where, 'variable missing in Figma'); continue; }
    if (fv.resolvedType !== ev.type) miss(where, 'type', ev.type, fv.resolvedType);
    const es = [...(ev.scopes || [])].sort().join(','), fs = [...fv.scopes].sort().join(',');
    if (es && es !== fs && !(fs === 'ALL_SCOPES')) miss(where, 'scopes', es, fs);
    else if (es && fs === 'ALL_SCOPES') miss(where, 'scopes (Figma has All)', es, fs);
    if (ev.codeSyntax && ev.codeSyntax.WEB && (fv.codeSyntax || {}).WEB !== ev.codeSyntax.WEB) miss(where, 'code syntax (WEB)', ev.codeSyntax.WEB, (fv.codeSyntax || {}).WEB || '—');
    for (const mode of ec.modes) {
      const m = fc.modes.find((x) => x.name === mode); if (!m) continue;
      summary.values++;
      const e = ev.values[mode]; const f = fv.valuesByMode[m.modeId];
      if (e && typeof e === 'object' && e.alias) {
        const target = f && f.type === 'VARIABLE_ALIAS' ? byId[f.id] : null;
        if (!target) miss(where + ' · ' + mode, 'should be an alias', e.alias, f && f.type ? f.type : JSON.stringify(f));
        else if (fullName(target) !== e.alias) miss(where + ' · ' + mode, 'alias points elsewhere', e.alias, fullName(target));
      } else if (ev.type === 'COLOR') {
        if (!f || f.type === 'VARIABLE_ALIAS') miss(where + ' · ' + mode, 'should be a raw colour', e, f && f.type === 'VARIABLE_ALIAS' ? 'alias → ' + fullName(byId[f.id]) : '—');
        else if (!sameColor(parseHex(e), f)) miss(where + ' · ' + mode, 'colour', e, toHex(f));
      } else if (f && f.type === 'VARIABLE_ALIAS') miss(where + ' · ' + mode, 'should be a raw value', e, 'alias → ' + fullName(byId[f.id]));
      else if (ev.type === 'FLOAT' ? Math.abs(f - e) > 0.001 : f !== e) miss(where + ' · ' + mode, 'value', e, f);
    }
  }
  for (const fv of fvars) if (!ec.variables.some((v) => v.name === fv.name)) miss(ec.name + '/' + fv.name, 'exists only in Figma (add to code or delete)', '—', fv.resolvedType);
}
for (const fc of cols) if (!EXPECTED.collections.some((c) => c.name === fc.name)) miss(fc.name, 'collection exists only in Figma', '—', fc.modes.map((m) => m.name).join(', '));
const styles = await figma.getLocalTextStylesAsync();
const W = { 100: 'Thin', 200: 'Extra Light', 300: 'Light', 400: 'Regular', 500: 'Medium', 600: 'Semi Bold', 700: 'Bold' };
for (const et of EXPECTED.textStyles) {
  summary['text styles']++;
  const fs = styles.find((s) => s.name === et.name);
  if (!fs) { miss('text/' + et.name, 'text style missing in Figma'); continue; }
  if (fs.fontName.family !== et.family) miss('text/' + et.name, 'font family', et.family, fs.fontName.family);
  if (et.weight && fs.fontName.style !== W[et.weight]) miss('text/' + et.name, 'font weight', W[et.weight], fs.fontName.style);
  for (const [prop, target] of Object.entries(et.bind || {})) {
    const b = (fs.boundVariables || {})[prop]; const t = b ? byId[b.id] : null;
    if (!t) miss('text/' + et.name, prop + ' not bound to a variable', target, '—');
    else if (fullName(t) !== target) miss('text/' + et.name, prop + ' bound elsewhere', target, fullName(t));
  }
}
for (const fs of styles) if (!EXPECTED.textStyles.some((s) => s.name === fs.name)) miss('text/' + fs.name, 'text style exists only in Figma', '—', fs.fontName.family + ' ' + fs.fontName.style);
return { ok: out.length === 0, checkedAt: Date.now(), summary, mismatches: out };
`;
writeFileSync(new URL('../dist/figma-parity.js', import.meta.url), checker);
console.log(`figma-parity.js written (${(checker.length / 1024).toFixed(1)} kB) — run it in Figma, save the result, then: node build/parity.mjs --report <file>`);
if (checker.length > 49000) { console.error('✗ parity script exceeds the 50 kB MCP limit'); process.exit(1); }
