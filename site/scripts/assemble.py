"""One-off: put the extracted DSGN logo into the static site.
Usage (from the project root): python3 -I assets/assemble.py
Reads assets/logo-parts.json, writes public/logo-motion.css and public/favicon.svg,
fills the <!--@…--> placeholders and the icon list in public/index.html."""
import json, re

p = json.load(open("assets/logo-parts.json"))

# tight viewBox for the static wordmark
nums = [float(n) for n in re.findall(r"-?\d+(?:\.\d+)?", p["static"])]
# path data mixes x/y pairs with H/V single values; take a safe box from the animated viewBox instead
vb = "7 -2 534 150"

sprite = ('<svg class="dsgn-visually-hidden" aria-hidden="true" focusable="false">'
          '<symbol id="dsgn-wordmark" viewBox="%s"><path d="%s"></path></symbol></svg>') % (vb, p["static"])

def paths(part):
    return "".join('<path%s d="%s"></path>' % (' class="r0"' if x["rest"] else "", x["d"]) for x in part["paths"])

word = ('<svg class="hero-logo logo-anim logo-wordmark" viewBox="%s" aria-hidden="true" focusable="false"><g>%s</g></svg>'
        % (p["wordmark"]["viewBox"], paths(p["wordmark"])))
mark = ('<svg class="cta-mark logo-anim logo-mark" viewBox="0 0 200 200" aria-hidden="true" focusable="false">'
        '<rect class="mark-bg" width="200" height="200"></rect><g>%s</g></svg>' % paths(p["mark"]))

def assign(cls, part):
    return "\n".join("  :root:not([data-motion=\"off\"]) .%s path:nth-child(%d) { animation-name: %s; }"
                     % (cls, i + 1, x["name"]) for i, x in enumerate(part["paths"]))

css = """/* DSGN logo motion — generated by assets/assemble.py from the Design canvas (v9 Final).
   CRT redraw: rows appear top-down, 56 ms per row, one glitch per 8 s loop.
   Offsets are %% of the SVG viewBox width (transform-box: view-box). Off with reduced motion or [data-motion="off"]. */

.logo-anim path { opacity: 0; transform-box: view-box; }
.logo-anim path.r0 { opacity: 1; }

@media (prefers-reduced-motion: no-preference) {
  :root:not([data-motion="off"]) .logo-anim path {
    animation-duration: 8s;
    animation-iteration-count: infinite;
    animation-fill-mode: both;
  }
%s
%s
}

%s
%s
""" % (assign("logo-wordmark", p["wordmark"]), assign("logo-mark", p["mark"]),
       p["keyframes"]["wordmark"], p["keyframes"]["mark"])
open("public/logo-motion.css", "w").write(css)

rows = p["symbolRows"]
fav = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 200">'
       '<rect width="200" height="200" fill="#191B1D"/><path fill="#F5F5F3" d="%s"/></svg>\n' % rows)
open("public/favicon.svg", "w").write(fav)

html = open("public/index.html").read()
html = html.replace("<!--@SPRITE-->", sprite).replace("<!--@WORDMARK_ANIM-->", word).replace("<!--@MARK_ANIM-->", mark)
icons = set(re.findall(r'class="dsgn-icon"[^>]*>([a-z0-9_]+)<', html)) | {"play_arrow", "check_circle", "warning", "info", "error"}
html = html.replace("icon_names=@ICONS", "icon_names=" + ",".join(sorted(icons)))
open("public/index.html", "w").write(html)
print(sorted(icons), len(html), len(css))
